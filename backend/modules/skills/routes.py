"""
Skill-driven AI endpoints
Each endpoint loads its matching MedNova skill as the system prompt
(see skills/mednova-integration-architecture/SKILL.md)
"""

import json
import logging
from typing import Any, Dict, List, Literal, Optional

from fastapi import APIRouter, HTTPException, Path
from pydantic import BaseModel, Field

from modules.skills.loader import load_skills
from modules.skills.runner import Draft, SkillRunnerError, skill_runner

logger = logging.getLogger(__name__)
router = APIRouter()

# Roles allowed to sign off each feature's drafts (human sign-off is a state, not a convention)
SIGN_OFF_ROLES: Dict[str, List[str]] = {
    "notes.soap": ["doctor"],
    "letters": ["doctor"],
    "coding.suggest": ["doctor", "billing"],
    "claims.precheck": ["billing", "admin"],
    "summaries": ["doctor", "nurse"],
    "schedule.propose": ["admin", "doctor", "nurse"],
}


class Requester(BaseModel):
    """Who is calling - recorded in the audit trail"""
    user_id: str = "anonymous"
    role: str = "doctor"
    patient_ref: Optional[str] = Field(None, description="Pseudonymous patient reference, never a name or ID number")


class SoapNoteRequest(Requester):
    transcript: str = Field(..., min_length=1)
    practice_type: Optional[str] = None
    patient_age: Optional[int] = None
    patient_sex: Optional[str] = None
    problem_list: Optional[str] = None
    output_language: str = "English"


class LetterRequest(Requester):
    document_type: Literal["referral", "scheme_motivation", "sick_note", "admin_email"] = "referral"
    source_notes: str = Field(..., min_length=1)
    recipient: Optional[str] = None
    urgency: Optional[Literal["Routine", "Soon", "Urgent", "Emergency"]] = None
    language: str = "English"


class CodingRequest(Requester):
    note: str = Field(..., min_length=1)
    coding_systems: str = "ICD-10 (WHO, South Africa) and CPT"
    funder: Optional[str] = None
    place_of_service: Optional[str] = None


class ClaimPrecheckRequest(Requester):
    claim: Dict[str, Any]
    clinical_note: Optional[str] = None
    scheme_rules: Optional[str] = None


class SummaryRequest(Requester):
    records: str = Field(..., min_length=1)
    instructions: Optional[str] = None


class ScheduleRequest(Requester):
    task: Literal["allocation", "no_show_risk", "reminders"]
    details: str = Field(..., min_length=1, description="Slots, rosters, requests or appointment list")
    channel: Optional[Literal["SMS", "WhatsApp", "email"]] = None
    language: str = "English"


class ReviewRequest(BaseModel):
    user_id: str
    role: str
    outcome: Literal["Accepted", "Edited", "Rejected"]


class DraftResponse(BaseModel):
    draft_id: str
    status: str
    feature: str
    skill: str
    model: str
    content: str
    structured: Optional[Dict[str, Any]] = None
    expires_at: str
    disclaimer: str = "Draft generated by MedNova AI - requires clinician review and sign-off."


def _section(title: str, value: Optional[Any]) -> str:
    return f"**{title}:** {value}\n" if value not in (None, "") else ""


def _to_response(draft: Draft) -> DraftResponse:
    return DraftResponse(
        draft_id=draft.id,
        status=draft.status,
        feature=draft.feature,
        skill=draft.skill,
        model=draft.model,
        content=draft.content,
        structured=draft.structured,
        expires_at=draft.expires_at.isoformat(),
    )


async def _run(feature: str, skill: str, content: str, req: Requester, schema: Optional[Dict[str, Any]] = None) -> DraftResponse:
    try:
        draft = await skill_runner.run(
            feature=feature,
            skill_name=skill,
            user_content=content,
            user_id=req.user_id,
            role=req.role,
            patient_ref=req.patient_ref,
            json_schema=schema,
        )
    except SkillRunnerError as e:
        raise HTTPException(status_code=e.status_code, detail=e.message)
    return _to_response(draft)


@router.get("/skills")
async def list_skills():
    """List installed MedNova skills"""
    return {
        "skills": [
            {"name": skill.name, "description": skill.description}
            for skill in load_skills().values()
        ]
    }


@router.post("/notes/soap", response_model=DraftResponse)
async def soap_note(req: SoapNoteRequest):
    """Consultation transcript -> SOAP note (mednova-soap-notes)"""
    content = (
        "Write a SOAP note for this consultation.\n\n"
        + _section("Patient reference", req.patient_ref)
        + _section("Practice type", req.practice_type)
        + _section("Patient age", req.patient_age)
        + _section("Patient sex", req.patient_sex)
        + _section("Existing problem list", req.problem_list)
        + _section("Output language", req.output_language)
        + f"\n<transcript>\n{req.transcript}\n</transcript>"
    )
    return await _run("notes.soap", "mednova-soap-notes", content, req)


@router.post("/letters", response_model=DraftResponse)
async def letter(req: LetterRequest):
    """Draft referral letters and admin correspondence (mednova-referral-letters)"""
    content = (
        f"Draft a {req.document_type.replace('_', ' ')}.\n\n"
        + _section("Patient reference", req.patient_ref)
        + _section("Recipient", req.recipient)
        + _section("Urgency", req.urgency)
        + _section("Language", req.language)
        + f"\n<source_notes>\n{req.source_notes}\n</source_notes>"
    )
    return await _run("letters", "mednova-referral-letters", content, req)


@router.post("/coding/suggest", response_model=DraftResponse)
async def coding_suggest(req: CodingRequest):
    """Suggest ICD-10 / procedure codes with evidence (mednova-clinical-coding)"""
    content = (
        "Suggest codes for this clinical note.\n\n"
        + _section("Coding systems", req.coding_systems)
        + _section("Funder / scheme", req.funder)
        + _section("Place of service", req.place_of_service)
        + f"\n<clinical_note>\n{req.note}\n</clinical_note>"
    )
    return await _run("coding.suggest", "mednova-clinical-coding", content, req)


@router.post("/claims/precheck", response_model=DraftResponse)
async def claims_precheck(req: ClaimPrecheckRequest):
    """Flag likely claim rejection reasons (mednova-billing-precheck)"""
    content = (
        "Pre-check this claim before submission.\n\n"
        f"<claim>\n{json.dumps(req.claim, indent=2, default=str)}\n</claim>\n"
        + (f"\n<clinical_note>\n{req.clinical_note}\n</clinical_note>\n" if req.clinical_note else "")
        + (f"\n<scheme_rules>\n{req.scheme_rules}\n</scheme_rules>\n" if req.scheme_rules else "\nNo scheme rules supplied.\n")
    )
    return await _run("claims.precheck", "mednova-billing-precheck", content, req)


def _nullable(kind: str) -> Dict[str, Any]:
    return {"type": [kind, "null"]}


def _items(properties: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "type": "array",
        "items": {
            "type": "object",
            "properties": properties,
            "required": list(properties.keys()),
            "additionalProperties": False,
        },
    }


# Mirrors the Mode 1 JSON in skills/mednova-clinical-summaries/SKILL.md
EXTRACTION_SCHEMA: Dict[str, Any] = {
    "type": "object",
    "properties": {
        "vitals": _items({"type": {"type": "string"}, "value": _nullable("string"), "unit": _nullable("string"), "recorded_at": _nullable("string"), "source": {"type": "string"}}),
        "medications": _items({"name": {"type": "string"}, "dose": _nullable("string"), "route": _nullable("string"), "frequency": _nullable("string"), "status": _nullable("string"), "source": {"type": "string"}}),
        "allergies": _items({"substance": {"type": "string"}, "reaction": _nullable("string"), "source": {"type": "string"}}),
        "procedures": _items({"name": {"type": "string"}, "date": _nullable("string"), "source": {"type": "string"}}),
        "results": _items({"test": {"type": "string"}, "value": _nullable("string"), "unit": _nullable("string"), "date": _nullable("string"), "source": {"type": "string"}}),
        "uncertain": _items({"field": {"type": "string"}, "reason": {"type": "string"}}),
    },
    "required": ["vitals", "medications", "allergies", "procedures", "results", "uncertain"],
    "additionalProperties": False,
}

SUMMARY_MODES = {
    "extraction": "Mode 1 - Structured extraction. Return only the JSON object.",
    "history": "Mode 2 - History summary.",
    "handover": "Mode 3 - Handover (SBAR).",
    "discharge": "Mode 3 - Discharge summary.",
}


@router.post("/summaries/{mode}", response_model=DraftResponse)
async def summaries(
    req: SummaryRequest,
    mode: Literal["extraction", "history", "handover", "discharge"] = Path(...),
):
    """Summaries and structured extraction (mednova-clinical-summaries)"""
    content = (
        f"{SUMMARY_MODES[mode]}\n\n"
        + _section("Patient reference", req.patient_ref)
        + _section("Additional instructions", req.instructions)
        + f"\n<records>\n{req.records}\n</records>"
    )
    schema = EXTRACTION_SCHEMA if mode == "extraction" else None
    return await _run("summaries", "mednova-clinical-summaries", content, req, schema)


SCHEDULE_TASKS = {
    "allocation": "Section 1 - Smart allocation. Propose a schedule and list requests that could not be placed and why.",
    "no_show_risk": "Section 2 - No-show risk flags. Score each appointment Low / Medium / High.",
    "reminders": "Section 3 - Reminders & patient messages.",
}


