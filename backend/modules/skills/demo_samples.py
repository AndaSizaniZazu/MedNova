def sample_for(feature: str, variant: Optional[str]) -> str:
    """Return the scripted draft for a feature and option"""
    sample = SAMPLES.get((feature, variant)) or SAMPLES.get((feature, None)) or GENERIC
    if feature == "notes.soap":
        sample = sample.format(date=datetime.now().strftime("%d %b %Y"))
    return sample
